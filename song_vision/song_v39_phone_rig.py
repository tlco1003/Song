"""SONG AI v39: observed voice-driven face and timed 3D phonetic gestures.

Only phone events from a *reviewed* alignment can be trusted as labels; other
sources are simulation previews. This controls the existing v35 3D object,
not a separate or assistant-faked MP4. Hidden tongue remains a prior.
"""
from __future__ import annotations
import dataclasses

CLOSED_BILABIALS = frozenset(("ㅁ", "ㅂ", "ㅃ", "ㅍ"))
NASALS = frozenset(("ㄴ", "ㅁ", "ㅇ"))
SIMPLE_CODA = frozenset(("ㄱ", "ㄴ", "ㄷ", "ㄹ", "ㅁ", "ㅂ", "ㅇ"))


def update_controls(base, event: dict | None, time_sec: float, *, vowel_pose, consonant_pose):
    """Apply a timed phone event to v37 predicted controls.

    `base` is already generated by the actual v37 learned owner model.
    Jaw angular proxy originates from *observed visible audio-visual learning*;
    the phoneme geometry of tongue, velum and skin remain articulatory priors.
    """
    if event is None:
        return dataclasses.replace(base, jaw_rad=max(.01, .22*base.jaw_rad),
                                   lip_open=.008, oral_stricture=0., oral_closure="none",
                                   velum_open=0., glottal_aspiration=0., laryngeal_tense=0.)
    slot = event.get("slot", "unknown")
    symbol = event.get("symbol", "")
    a, b = float(event["start"]), float(event["end"])
    p = max(0., min(1., (time_sec-a)/max(.004, b-a)))
    if slot == "unknown":
        return base # guard: never hallucinate 3D tongue from unrecognized IPA
    if slot == "vowel":
        try:
            target=vowel_pose(symbol, progress=p)
        except TypeError:
            target=vowel_pose(symbol)
        except ValueError:
            return base
        fields={name:getattr(target,name) for name in
                ("tip_z", "blade_z", "body_z", "dorsum_z", "root_z", "velum_open")}
        # Owner-specific visible lip motion is preserved, while the vowel target
        # provides an accent-independent 3-D tongue posture and rounding.
        fields["lip_protrusion"]=float(.65*target.lip_protrusion+.35*base.lip_protrusion)
        fields.update(oral_closure="none",oral_stricture=0.,tongue_groove=0.,
                      glottal_aspiration=0.,laryngeal_tense=0.)
        return dataclasses.replace(base,**fields).validate()
    if slot not in ("onset", "coda"):
        return base
    # A final ㅇ is the nasal [ŋ], not the silent onset ㅇ.
    if slot == "coda" and symbol == "ㅇ":
        target=consonant_pose("ㄱ", "ㅏ")
        target=dataclasses.replace(target,velum_open=1.,oral_closure="velar",oral_stricture=1.)
    elif slot == "coda" and symbol not in SIMPLE_CODA:
        # Korean final clusters need verified surface realization; do not guess.
        raise ValueError("Complex coda cannot be driven from spelling without a reviewed surface phone")
    else:
        target=consonant_pose(symbol, "ㅏ")
    # Initial stop/fricative contact is maintained, then released into vowel.
    # Word-final coda is approached instead of released (without audio-grounded
    # consonant release timing, the interval itself is the only available cue).
    if slot == "onset":
        strength=1. if p<.64 else max(0., (1.-p)/.36)
    else:
        strength=min(1.,p/.30)
    state={}
    for field in ("tip_z","blade_z","body_z","dorsum_z","root_z",
                  "velum_open","glottal_aspiration","laryngeal_tense","tongue_groove"):
        state[field]=float(strength*getattr(target,field)+(1-strength)*getattr(base,field))
    if target.oral_closure=="bilabial":
        state["lip_open"]=float(max(.002,base.lip_open*(1-strength)))
        state["lip_width"]=float(.68*base.lip_width+.32*target.lip_width)
    if strength>.20:
        state["oral_closure"]=target.oral_closure
        state["oral_stricture"]=float(strength*target.oral_stricture)
    else:
        state["oral_closure"]="none"
        state["oral_stricture"]=0.
    return dataclasses.replace(base,**state).validate()
