import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createApp} from '../src/server.mjs';
test('GET UI and GPT/Suno config without provider credentials',async()=>{
  const app=createApp();
  await new Promise(resolve=>app.listen(0,'127.0.0.1',resolve));
  const url='http://127.0.0.1:'+app.address().port;
  try{
    let health=await fetch(url+'/healthz');
    assert.equal(health.status,200);
    assert.deepEqual(await health.json(),{status:'ok',service:'withu-api'});
    let res=await fetch(url+'/');
    assert.equal(res.status,200);
    assert.match(await res.text(),/세상에서 하나뿐인 당신의 노래로/);
    res=await fetch(url+'/create.html');
    assert.equal(res.status,200);
    assert.match(await res.text(),/나만의 노래 만들기/);
    res=await fetch(url+'/create.js');
    assert.equal(res.status,200);
    res=await fetch(url+'/create.css');
    assert.equal(res.status,200);
    res=await fetch(url+'/media/mother-song.mp4',{method:'HEAD'});
    assert.equal(res.status,200); // Uploaded video is now published in docs/media.
    assert.equal(res.headers.get('content-type'),'video/mp4');
    res=await fetch(url+'/checkout.html');
    assert.equal(res.status,200);
    assert.match(await res.text(),/노래 선물 선택/);
    res=await fetch(url+'/payment.html');
    assert.equal(res.status,200);
    assert.match(await res.text(),/WITHU — 결제/);
    res=await fetch(url+'/payment.js');
    assert.equal(res.status,200);
    assert.match(await res.text(),/confirm-checkout/);
    res=await fetch(url+'/music-genres.json');
    assert.equal(res.status,200);
    assert.equal((await res.json()).genres.length,7);
    res=await fetch(url+'/checkout.css');
    assert.equal(res.status,200);
    res=await fetch(url+'/checkout.js');
    assert.equal(res.status,200);
    res=await fetch(url+'/checkout-media.js');
    assert.equal(res.status,200);
    assert.match(res.headers.get('content-type'),/javascript/);
    assert.match(await res.text(),/MediaRecorder/);
    assert.match(res.headers.get('permissions-policy'),/camera=\(self\)/);
    assert.match(res.headers.get('content-security-policy'),/img-src 'self' data: blob:/);

    res=await fetch(url+'/api/commerce/readiness');
    assert.equal(res.status,200);
    const commerce=await res.json();
    assert.equal(commerce.canCharge,false);
    assert.equal(commerce.licenseVerified,false);
    res=await fetch(url+'/prices.json');
    assert.equal(res.status,200);
    const prices=await res.json();
    assert.equal(prices.currency,'KRW');
    assert.deepEqual(prices.products.map(p=>p.amountKrw),[29000,39000,300000]);
    assert.equal(prices.products[2].quoteRequired,true);
    res=await fetch(url+'/api/commerce/catalog');
    assert.equal(res.status,200);
    assert.deepEqual(await res.json(),prices);
    res=await fetch(url+'/api/commerce/orders',{method:'POST',headers:{'Content-Type':'application/json'},
      body:JSON.stringify({email:'test@example.com',amount:1})});
    assert.equal(res.status,503); // Must not charge or retain email.
    res=await fetch(url+'/studio');
    assert.equal(res.status,200);
    assert.match(await res.text(),/내 이야기가/);
    res=await fetch(url+'/media/lyrics-nara.txt',{headers:{Range:'bytes=0-19'}});
    assert.equal(res.status,206);
    assert.match(res.headers.get('content-range'),/^bytes 0-19\//);
    assert.equal((await res.arrayBuffer()).byteLength,20);
    res=await fetch(url+'/media/tracks.json');
    assert.equal(res.status,200);
    const publishedTracks=(await res.json()).tracks;
    assert.ok(publishedTracks.length>=7);
    assert.ok(publishedTracks.some(track=>track.id==='song-sprout'&&track.title==='씨앗을심어'));
    assert.ok(publishedTracks.some(track=>track.id==='song-am630'&&track.title==='새벽여섯시반'));
    res=await fetch(url+'/docs/IMPLEMENTATION.md');
    assert.equal(res.status,404);
    res=await fetch(url+'/가사 프롬프트.md');
    assert.equal(res.status,404);
    res=await fetch(url+'/api/config');
    assert.equal(res.status,200);
    const config=await res.json();
    assert.equal(config.lyricsProvider,'openai');
    assert.equal(config.musicProvider,'suno-mcp');
    assert.equal(typeof config.lyricsReady,'boolean');
    assert.equal(config.sunoMcpUrl,'https://api.suno.com/mcp');
    res=await fetch(url+'/api/jobs',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({story:'hello'})});
    assert.equal(res.status,410);
    res=await fetch(url+'/api/unknown');
    assert.equal(res.status,404);
    res=await fetch(url+'/../package.json');
    assert.equal(res.status,404);
  }finally{await new Promise(resolve=>app.close(resolve));}
});
